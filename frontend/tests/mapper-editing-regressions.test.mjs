test('duplicating a repeating structure creates an independent empty occurrence even before mapping',async()=>{
  const helper=await readFile(new URL('../src/mapperLoopMappings.ts',import.meta.url),'utf8');
  const compiled=ts.transpileModule(helper,{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
  const {emptyRepeatOccurrence}=await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
  let declaration;
  function visit(node) {if(ts.isVariableDeclaration(node)&&node.name.getText(ast)==='duplicateOccurrence') declaration=node;ts.forEachChild(node,visit);}
  visit(ast);
  for(const operator of [undefined,'copy-of','for-each','for-each-group']) {
    const parent=operator && {target:'Record',operator,source:'${input.rows}',select:'${input.rows}',groupBy:'name',functions:['trim'],constant:'old',condition:'true'};
    const child={target:'Record.Name',source:'${input.rows.Name}',autoGenerated:true};
    const mappings=parent ? [parent,child] : [];
    let result;
    const context=vm.createContext({fields:[{path:'Record',repeating:true,type:'RecordType[]'}],mappings,emptyRepeatOccurrence,crypto:{randomUUID:()=> 'new-copy'},setMappings:v=>result=v});
    vm.runInContext(compile(`const ${declaration.getText(ast)}; duplicateOccurrence('Record'); duplicateOccurrence('Record.Name');`),context);
    assert.equal(result.length,mappings.length+1);
    mappings.forEach((rule,index)=>assert.equal(result[index],rule));
    const copy=result.at(-1);assert.equal(copy.source,'');assert.equal(copy.operator,operator === 'for-each-group' ? operator : 'for-each');
    assert.equal(copy.occurrenceId,'occurrence-new-copy');assert.equal(copy.duplicateOf,'primary');
    for(const key of ['select','constant','condition','autoGenerated']) assert.equal(copy[key],undefined);
    assert.equal(copy.functions.length,0);
    if(operator==='for-each-group') assert.equal(copy.groupBy,'');
  }
});

test('the context menu offers Duplicate mapping for an unmapped repeat and follows target and group rules',()=>{
  const fn=ast.statements.find(s=>s.name?.text==='MappingContextMenu');
  const context=vm.createContext({
    React:{createElement:(type,props,...children)=>({type,props,children:children.flat(Infinity)})},
    createPortal:content=>content, document:{body:{}}, window:{innerWidth:800,innerHeight:800}, DataNodeIcon:'icon',
    useRef:()=>({current:null}), useState:()=>[null,()=>{}], useEffect:()=>{}, mappingSource:value=>value,
  });
  const grouped=ast.statements.find(s=>s.name?.text==='defaultGroupedLoopSource');
  vm.runInContext(compile(`${fn.getText(ast)}\n${grouped.getText(ast)}`),context);
  const parent={key:'group',kind:'loop',rule:{operator:'for-each-group'}};
  assert.equal(context.defaultGroupedLoopSource({ancestors:['group']},[parent]),'current-group()');
  assert.equal(context.defaultGroupedLoopSource({ancestors:['group'],loopKey:'group'},[parent]),undefined);
  let copies=0, rule;
  const menu=(label,canDuplicate, options={})=>all(context.MappingContextMenu({menu:{label:'Record',x:0,y:0,...options},canDuplicate,
    duplicate:()=>copies++,change:value=>rule=value,close() {}})).find(node=>node.type==='button'&&node.children.includes(label));
  assert.equal(menu('Duplicate mapping',true).props.disabled,false);
  menu('Duplicate mapping',true).props.onClick();
  assert.equal(copies,1);
  assert.equal(menu('Duplicate mapping',false).props.disabled,true);
  assert.equal(menu('If…',true,{required:true}).props.disabled,true);
  assert.ok(!menu('If…',true,{required:false}).props.disabled);
  menu('For Each…',true,{defaultLoopSource:'current-group()'}).props.onClick();
  assert.equal(rule.source,'current-group()');
});
