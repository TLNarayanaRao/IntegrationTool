type Field = {path:string; type?:string; repeating?:boolean};
export type RepeatingDropMode = 'copy-of' | 'smart-map' | 'for-each';

export function emptyRepeatOccurrence(target: string, targetType: string | undefined, occurrenceId: string, selectedOccurrence?: string, previous?: any) {
  const grouped = previous?.operator === 'for-each-group';
  return {target, targetType, source:'', operator:grouped ? 'for-each-group' : 'for-each',
    ...(grouped ? {groupBy:''} : {}), functions:[], enabled:true, occurrenceId,
    parentOccurrenceId:previous?.duplicateOf ? previous.parentOccurrenceId : selectedOccurrence,
    duplicateOf:selectedOccurrence || 'primary'};
}

export function removeRepeatOccurrence(mappings: any[], occurrenceId: string) {
  const removed = new Set([occurrenceId]);
  for (const id of removed) for (const rule of mappings) {
    if (rule.parentOccurrenceId === id && rule.occurrenceId) removed.add(rule.occurrenceId);
  }
  return mappings.filter(rule => !removed.has(rule.occurrenceId));
}

/** Clear a target subtree in its occurrence, including nested duplicate branches. */
export function removeMappingSubtree(mappings: any[], target: string, occurrenceId?: string, duplicateRoot = false) {
  if (duplicateRoot && occurrenceId) return removeRepeatOccurrence(mappings, occurrenceId);
  const below = (path: string) => path.startsWith(target + '.');
  const removedOccurrences = new Set<string>();
  const occurrenceRoots = new Map<string, any>();
  for (const rule of mappings) {
    if (!rule.occurrenceId) continue;
    const root = occurrenceRoots.get(rule.occurrenceId);
    if (!root || rule.target.length < root.target.length) occurrenceRoots.set(rule.occurrenceId, rule);
  }
  for (const rule of occurrenceRoots.values()) {
    if (rule.parentOccurrenceId === occurrenceId && below(rule.target)) {
      removedOccurrences.add(rule.occurrenceId);
    }
  }
  for (const id of removedOccurrences) for (const rule of mappings) {
    if (rule.parentOccurrenceId === id && rule.occurrenceId) removedOccurrences.add(rule.occurrenceId);
  }
  return mappings.filter(rule => !removedOccurrences.has(rule.occurrenceId) &&
    !(rule.occurrenceId === occurrenceId && (rule.target === target || below(rule.target))));
}

/** Match relative schema paths, preserving source spelling and explicit user mappings. */
export function autoMapLoopChildren(fields:Field[], mappings:any[], target:string, expression:any, sources:any[], occurrenceId?:string, smart = false):any[] {
  const next=mappings.filter(rule=>!(rule.occurrenceId===occurrenceId && rule.autoGenerated && rule.target.startsWith(`${target}.`)));
  if (typeof expression !== 'string') return next;
  const path = expression.match(/^\$\{([^}]+)\}$/)?.[1];
  if (!path) return next;
  let root = '', source:any;
  const legacy = path.match(/^activities\.([^.]+)\.output(?:\.(.*))?$/);
  const named = sources.find(s => s.prefix && (path === s.prefix || path.startsWith(s.prefix + '.')));
  if (named) { source = named; root = path.slice(named.prefix.length + 1); }
  else if (legacy) { source=sources.find(s=>s.activity?.id===legacy[1]);root=legacy[2] || ''; }
  else {
    const [name,...parts]=path.split('.'); root=parts.join('.');
    source=sources.find(s=>name==='input' ? s.activity?.type==='start' : name==='last' ? s.distance===1 : s.reference===name || s.activity?.id===name);
  }
  if (!source) return next;
  const prefix=root ? `${root}.` : '';
  const candidates=new Map<string,any[]>(), normalized=new Map<string,any[]>();
  const normalize = (key:string) => key.replace(/[-_]/g, '');
  for (const field of source.fields) {
    if (!field.key.toLowerCase().startsWith(prefix.toLowerCase())) continue;
    const relative=field.key.slice(prefix.length), key=relative.toLowerCase();
    const matches=candidates.get(key)||[];matches.push({field,relative});candidates.set(key,matches);
    if (smart) {
      const keyName = normalize(key), alternatives = normalized.get(keyName) || [];
      alternatives.push({field,relative});normalized.set(keyName,alternatives);
    }
  }
  if (!candidates.size) return next;
  const existing=new Set(next.filter(rule=>rule.occurrenceId===occurrenceId).map(rule=>rule.target));
  const parents=new Set(fields.flatMap(field=>{const parts=field.path.split('.');return parts.slice(0,-1).map((_,i)=>parts.slice(0,i+1).join('.'));}));
  for (const field of fields) {
    if (!field.path.startsWith(`${target}.`) || existing.has(field.path)) continue;
    const key = field.path.slice(target.length+1).toLowerCase();
    const matches=candidates.get(key) ?? (smart ? normalized.get(normalize(key)) : undefined);
    if (matches?.length!==1) continue;
    if (parents.has(field.path) && !field.repeating) continue;
    const source=`\${${path}.${matches[0].relative}}`;
    next.push({target:field.path,source,targetType:field.type||'any',occurrenceId,functions:[],enabled:true,autoGenerated:true,
      ...(parents.has(field.path) && field.repeating ? {operator:'for-each',select:source} : {})});
  }
  return next;
}

export function mapRepeatingDrop(fields:Field[], mappings:any[], target:string, source:string, sources:any[], mode:RepeatingDropMode, occurrenceId?:string) {
  const field = fields.find(entry => entry.path === target);
  if (!field?.repeating) return mappings;
  const below = (rule:any) => rule.target.startsWith(target + '.');
  const hidden = new Set<string>();
  if (mode === 'copy-of') {
    const copies = mappings.filter(rule => rule.occurrenceId && rule.duplicateOf && below(rule));
    const collect = (owner?:string) => {
      for (const copy of copies) if (copy.parentOccurrenceId === owner && !hidden.has(copy.occurrenceId)) {
        hidden.add(copy.occurrenceId);
        collect(copy.occurrenceId);
      }
    };
    collect(occurrenceId);
  }
  const previous = mappings.find(rule => rule.target === target && rule.occurrenceId === occurrenceId);
  const replacement = {target, source, targetType:field.type || 'any', occurrenceId, functions:[], enabled:true,
    ...(previous?.duplicateOf ? {duplicateOf:previous.duplicateOf, parentOccurrenceId:previous.parentOccurrenceId} : {}),
    ...(mode === 'copy-of' ? {operator:'copy-of'} : {operator:'for-each', select:source})};
  const next = mappings.filter(rule => !hidden.has(rule.occurrenceId) &&
    !(mode === 'copy-of' && rule.occurrenceId === occurrenceId && below(rule)))
    .map(rule => rule === previous ? replacement : rule);
  if (!previous) next.push(replacement);
  return mode === 'copy-of' ? next : autoMapLoopChildren(fields, next, target, source, sources, occurrenceId, mode === 'smart-map');
}

const occurrencesKey = '$occurrences';

export function activityMappingRules(mappings:Record<string, any>): any[] {
  const primary = Object.entries(mappings).filter(([path]) => path !== occurrencesKey).map(([target,value]) =>
    value && typeof value === 'object' && value.$rule ? {...value,target,operator:value.$rule,inputValue:value}
      : {target,source:value,inputValue:value});
  return [...primary, ...(Array.isArray(mappings[occurrencesKey]) ? mappings[occurrencesKey] : [])];
}

export function activityMappingsFromRules(rules:any[]) {
  const entries:[string,any][] = [], copies:any[] = [];
  for (const rule of rules) {
    const {target, operator, inputValue, ...value} = rule;
    if (rule.occurrenceId) copies.push({target,operator,...value});
    else if ('inputValue' in rule) entries.push([target,inputValue]);
    else if (operator || rule.autoGenerated) {
      const {source, select, mapChildren, smartMatch, autoGenerated} = value;
      entries.push([target,{$rule:operator || 'direct',source,...(select ? {select} : {}),...(mapChildren ? {mapChildren} : {}),
        ...(smartMatch ? {smartMatch} : {}),...(autoGenerated ? {autoGenerated} : {})}]);
    }
    else entries.push([target,rule.source]);
  }
  if (copies.length) entries.push([occurrencesKey,copies]);
  return Object.fromEntries(entries);
}

/** Bridge the shared schema mapper to activities' existing path-keyed bindings. */
export function mapActivityRepeatingDrop(fields:Field[], mappings:Record<string, any>, target:string, source:string, sources:any[], mode:RepeatingDropMode, occurrenceId?:string) {
  const prefix = target + '.';
  const rules = activityMappingRules(mappings).filter(rule => occurrenceId || rule.occurrenceId || !rule.target.startsWith(prefix)
    || !/^\d+(?:\.|$)/.test(rule.target.slice(prefix.length)));
  const original = new Set(rules);
  return activityMappingsFromRules(mapRepeatingDrop(fields,rules,target,source,sources,mode,occurrenceId).map(rule => original.has(rule) ? rule : {
    ...rule,
    ...(rule.operator === 'for-each' && fields.some(field => field.path.startsWith(rule.target + '.')) ? {mapChildren:true} : {}),
    ...(mode === 'smart-map' && rule.target === target ? {smartMatch:true} : {}),
  }));
}

export function relativeLoopExpression(value:any, scope?:string):any {
  if (!scope || typeof value!=='string') return value;
  const root=scope.match(/^\$\{([^}]+)\}$/)?.[1], path=value.match(/^\$\{([^}]+)\}$/)?.[1];
  return root && path?.startsWith(`${root}.`) ? path.slice(root.length+1) : value;
}

export function expandLoopExpression(value:any, scope?:string, paths?:string[]):any {
  const root=scope?.match(/^\$\{([^}]+)\}$/)?.[1];
  // Only plain relative paths are expanded; literals, functions and explicit references are untouched.
  const path = root && typeof value==='string' ? `${root}.${value}` : '';
  return root && typeof value==='string' && /^[A-Za-z_@][\w.@-]*$/.test(value) && !['true','false','null'].includes(value)
    && (!paths || paths.includes(path)) ? `\${${path}}` : value;
}
