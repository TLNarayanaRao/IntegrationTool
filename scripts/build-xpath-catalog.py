"""Generate the designer fallback from MINA's executable XPath inventory."""
import argparse
import json
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'backend'))
from app.mapper_xml import xpath_function_palette

def generate():
    catalog={version:xpath_function_palette(version) for version in ('1.0','2.0')}
    return ('// Generated by scripts/build-xpath-catalog.py; do not hand-edit the inventory.\n'
        'export type XPathFunction = {name:string;args:string[];category:string;signature:string;description:string};\n'
        'export const xpathCatalog: Record<string,XPathFunction[]> = '+json.dumps(catalog,indent=2)+';\n')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    output=ROOT/'frontend/src/xpath-catalog.ts';text=generate()
    if args.check:
        if output.read_text(encoding='utf-8').replace('\r\n','\n')!=text:raise SystemExit('XPath catalog is stale; run scripts/build-xpath-catalog.py in the backend environment')
        print('Designer XPath inventory matches the runtime.')
    else:output.write_text(text,encoding='utf-8');print('Generated full designer XPath inventory.')
