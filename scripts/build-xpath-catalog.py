"""Generate the designer fallback from MINA's executable XPath inventory."""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'backend'))
from app.mapper_xml import parse_xml, xpath_function_palette, xpath_value
from xpath_help_examples import (ARGUMENTS, CONSTRUCTORS, CONTEXT_EXPRESSIONS, CONTEXT_ITEM_FUNCTIONS,
                                DATE, DATETIME, DESCRIPTIONS, DURATION, OVERLOADS, TIME,
                                VARIABLE_RESULTS, XML)


def example_for(entry, version, root):
    name, arity = entry['name'], len(entry['args'])
    if name.startswith('xs:'):
        args = [f"'{CONSTRUCTORS[name[3:]]}'"]
    elif '-from-' in name and name.split('-from-')[1] in ('date', 'dateTime', 'time', 'duration'):
        args = [dict(date=DATE, dateTime=DATETIME, time=TIME, duration=DURATION)[name.split('-from-')[1]]]
    else:
        args = list(OVERLOADS.get((name, arity), ARGUMENTS.get(name, ())[:arity]))
    if len(args) != arity:
        raise ValueError(f'XPath {version} {name}#{arity} needs sample inputs')
    call = f'{name}({", ".join(args)})'
    expression = CONTEXT_EXPRESSIONS.get(name, call)
    context_item = not arity and name in CONTEXT_ITEM_FUNCTIONS
    source = '<p:item xmlns:p="urn:mina:example" xml:base="https://example.org/orders/">  12  </p:item>' if context_item else XML
    properties = {'region': 'us-east'} if name == 'project:getModuleProperty' else {}
    note = ''
    try:
        result = xpath_value(parse_xml(source) if context_item else root, expression, version, {}, properties=properties)
    except ValueError as error:
        if name != 'resolve-uri' or arity != 1 or '[err:FONS0005]' not in str(error):
            raise ValueError(f'XPath {version} {expression}: {error}') from error
        note = 'Standalone mappings have no static base URI. Use the two-argument form to supply one explicitly.'
        result = None
    example = {'args': args, 'expression': expression, 'result': json.dumps(result, ensure_ascii=False, allow_nan=False)}
    if note:
        example.update(result='FONS0005 · No static base URI', note=note, error=True)
    if '/' in expression and (re.search(r'(?<![\w:/])/(?:orders|[,)])', expression) or name == 'document-uri') \
            or context_item or name == 'lang':
        example['xml'] = source
    if name == 'xs:QName':
        example['xml'] = XML
    if properties:
        example['properties'] = properties
    if name in VARIABLE_RESULTS:
        sample, pattern, note = VARIABLE_RESULTS[name]
        if not re.fullmatch(pattern, str(result)):
            raise ValueError(f'Unexpected variable result for {name}: {result!r}')
        example.update(result=json.dumps(sample), note=note, variable=True)
    if name == 'static-base-uri':
        example['note'] = 'A standalone expression has no configured static base URI, so this example returns an empty sequence.'
    if name == 'document-uri':
        example['note'] = 'Inline XML has no document URI, so this example returns an empty sequence.'
    if name == 'idref':
        example['note'] = 'The sample document has no typed ID references, so the result is an empty sequence.'
    if name == 'unordered':
        example['note'] = 'This evaluation retained the input order. Do not rely on a particular order.'
    if name in {'default-collation', 'in-scope-prefixes'}:
        example['note'] = 'This value reflects the sample evaluation context.'
    return example

def generate():
    catalog={version:xpath_function_palette(version) for version in ('1.0','2.0')}
    root = parse_xml(XML)
    for version, entries in catalog.items():
        catalog[version] = [
            {**entry, 'description': DESCRIPTIONS.get(entry['name'], entry['description']),
             'example': example_for(entry, version, root)}
            for entry in entries
        ]
    return ('// Generated by scripts/build-xpath-catalog.py; do not hand-edit the inventory.\n'
        'export type XPathExample = {args:string[];expression:string;result:string;xml?:string;properties?:Record<string,string>;note?:string;error?:boolean;variable?:boolean};\n'
        'export type XPathFunction = {name:string;args:string[];category:string;signature:string;description:string;example?:XPathExample};\n'
        'export const xpathCatalog: Record<string,(XPathFunction & {example:XPathExample})[]> = '+json.dumps(catalog,indent=2)+';\n')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    output=ROOT/'frontend/src/xpath-catalog.ts';text=generate()
    if args.check:
        if output.read_text(encoding='utf-8').replace('\r\n','\n')!=text:raise SystemExit('XPath catalog is stale; run scripts/build-xpath-catalog.py in the backend environment')
        print('Designer XPath inventory matches the runtime.')
    else:output.write_text(text,encoding='utf-8');print('Generated full designer XPath inventory.')
